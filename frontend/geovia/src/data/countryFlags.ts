export const countryFlags: CountryFlag[] = Object.entries(flagCodes).map(
  ([countryId, isoCode]) => ({
    countryId,
    isoCode,
    imageUrl: `https://flagcdn.com/w160/${isoCode}.png`,
  }),
)

export function getCountryFlag(countryId: string): CountryFlag | undefined {
  return countryFlags.find((flag) => flag.countryId === countryId)
}
